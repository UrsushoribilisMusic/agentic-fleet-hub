#!/usr/bin/env python3
"""
CE-06b: does surface-matching the negative controls change the disposition results?

Runs three comparisons across apertus / ministral / qwen:

  A. Argmax recall per class (arm1 = J-space only, arm2 = production pipeline)
  B. Discriminability of positives vs negatives, in SEED-SCORE space:
       - vs v1 negatives        (split="negative",         unmatched, n=20/class)
       - vs matched negatives   (split="negative_matched", matched,   n=50/class)
  C. The same discriminability, but on the RAW TAP-LAYER HIDDEN STATE (h_tap).

Why C matters: B measures whether a disposition is recoverable *through the
seed-vector projection*. C measures whether it is present in the representation
at all. A class that scores low on B and high on C is a lens failure. A class
that scores low on both is genuinely not represented. Without C the two are
indistinguishable, and "small models cannot sense mischief" is unfalsifiable.

Usage:
    python3 eval/ce06b_matched_negative_analysis.py \
        [--models apertus,ministral,qwen] \
        [--out eval/canis_eval001_ce06b_report.md]
"""

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import StratifiedKFold, cross_val_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

CLASSES = ["confident", "uncertain", "curious", "concern", "reluctant", "warm", "mischief"]
ALL_CLASSES = CLASSES + ["idle"]
# The 7 seed-vector axes. idle has no seed vector by design, so it is not a feature.
FEATURES = CLASSES

CV = StratifiedKFold(5, shuffle=True, random_state=0)


def cv_score(X, y):
    """Balanced accuracy under 5-fold CV. 0.50 == indistinguishable."""
    if len(set(y)) < 2 or min(Counter(y).values()) < 5:
        return None, None
    clf = make_pipeline(StandardScaler(), LogisticRegression(max_iter=5000, class_weight="balanced"))
    s = cross_val_score(clf, X, y, cv=CV, scoring="balanced_accuracy")
    return float(s.mean()), float(s.std())


def load_results(model, results_dir):
    path = results_dir / f"results_canis_eval001_{model}.jsonl"
    rows = [json.loads(l) for l in open(path) if l.strip()]
    # Guard against a partially-appended file being analysed as if complete.
    seen, uniq = set(), []
    for r in rows:
        if r["item_id"] in seen:
            continue
        seen.add(r["item_id"])
        uniq.append(r)
    return uniq


def load_h_tap(model, results_dir):
    path = results_dir / f"h_tap_canis_eval001_{model}.jsonl"
    if not path.exists():
        return {}
    out = {}
    for line in open(path):
        if not line.strip():
            continue
        d = json.loads(line)
        out[d["item_id"]] = np.asarray(d["h_tap"], dtype=np.float32)
    return out


def seed_features(rows):
    return np.array([
        [r["seed_scores"].get(f, 0.0) for f in FEATURES] + [r.get("entropy_norm") or 0.0]
        for r in rows
    ])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", default="apertus,ministral,qwen")
    ap.add_argument("--results-dir", default="eval")
    ap.add_argument("--out", default="eval/canis_eval001_ce06b_report.md")
    args = ap.parse_args()

    models = [m.strip() for m in args.models.split(",") if m.strip()]
    rdir = Path(args.results_dir)
    L = []          # report lines
    def w(s=""): L.append(s)

    w("# CANIS-EVAL-001 — CE-06b: matched negative controls")
    w()
    w("Generated by `eval/ce06b_matched_negative_analysis.py`.")
    w()
    w("`negative` = v1 controls (unmatched, n=20/class). `negative_matched` = CE-03b "
      "controls (topic+vocabulary matched, n=50/class). Scores are balanced accuracy "
      "under 5-fold CV; **0.50 means indistinguishable**.")
    w()

    summary = defaultdict(dict)

    for model in models:
        rows = load_results(model, rdir)
        htap = load_h_tap(model, rdir)
        by_split = Counter(r["split"] for r in rows)
        w(f"## {model}")
        w()
        w(f"Loaded {len(rows)} rows — " + ", ".join(f"{k}={v}" for k, v in sorted(by_split.items())))
        if htap:
            dim = len(next(iter(htap.values())))
            w(f"h_tap available for {len(htap)} items (dim={dim}).")
        else:
            w("h_tap sidecar missing — section C skipped for this model.")
        w()

        pos_all = [r for r in rows if r["split"] == "positive"]
        idle    = [r for r in rows if r["split"] == "idle"]

        # ---------------- A. argmax recall ----------------
        w("### A. Argmax recall per class")
        w()
        w("| class | n | arm1 (J-space) | arm2 (production) | top arm1 confusion |")
        w("|---|---|---|---|---|")
        for c in ALL_CLASSES:
            items = [r for r in (pos_all + idle) if r["target_class"] == c]
            if not items:
                continue
            a1 = sum(1 for r in items if r["arm1"] == c) / len(items)
            a2 = sum(1 for r in items if r["arm2"] == c) / len(items)
            conf = Counter(r["arm1"] for r in items if r["arm1"] != c)
            top = ", ".join(f"{k}:{v}" for k, v in conf.most_common(2)) or "—"
            w(f"| `{c}` | {len(items)} | {a1*100:.0f}% | {a2*100:.0f}% | {top} |")
        w()
        for arm in ("arm1", "arm2"):
            acc = sum(1 for r in pos_all if r[arm] == r["target_class"]) / len(pos_all)
            w(f"- **{arm} pooled positive accuracy: {acc*100:.1f}%** (n={len(pos_all)})")
        w()

        # ---------------- B & C. discriminability ----------------
        w("### B/C. Positive vs negative discriminability")
        w()
        w("| class | seed-space vs v1 | seed-space vs matched | Δ | h_tap vs matched |")
        w("|---|---|---|---|---|")
        for c in CLASSES:
            pos = [r for r in rows if r["target_class"] == c and r["split"] == "positive"]
            n_v1 = [r for r in rows if r["target_class"] == c and r["split"] == "negative"]
            n_mt = [r for r in rows if r["target_class"] == c and r["split"] == "negative_matched"]

            def seed_pair(neg):
                if not neg:
                    return None, None
                X = seed_features(pos + neg)
                y = np.array([1] * len(pos) + [0] * len(neg))
                return cv_score(X, y)

            v1_mu, v1_sd = seed_pair(n_v1)
            mt_mu, mt_sd = seed_pair(n_mt)

            ht_mu = ht_sd = None
            if htap and n_mt:
                sub = [r for r in pos + n_mt if r["item_id"] in htap]
                if len(sub) > 20:
                    X = np.stack([htap[r["item_id"]] for r in sub])
                    y = np.array([1 if r["split"] == "positive" else 0 for r in sub])
                    ht_mu, ht_sd = cv_score(X, y)

            def fmt(mu, sd):
                return "—" if mu is None else f"{mu:.3f} ±{sd:.2f}"
            delta = "—" if (v1_mu is None or mt_mu is None) else f"{mt_mu - v1_mu:+.3f}"
            w(f"| `{c}` | {fmt(v1_mu, v1_sd)} | {fmt(mt_mu, mt_sd)} | {delta} | {fmt(ht_mu, ht_sd)} |")

            summary[model][c] = {"v1": v1_mu, "matched": mt_mu, "h_tap": ht_mu}
        w()

    # ---------------- verdict ----------------
    w("## Verdict on the pre-registered prediction")
    w()
    w("> If v1 scores were inflated by unmatched negatives, EVERY class drops "
      "substantially against the matched set. If only `mischief` stays low, mischief "
      "is intrinsically hard and the methodological critique is much narrower.")
    w()
    w("| model | mean Δ (all classes) | mean Δ excluding mischief | mischief Δ | classes dropping >0.05 |")
    w("|---|---|---|---|---|")
    for model in models:
        d = {c: v for c, v in summary[model].items()
             if v["v1"] is not None and v["matched"] is not None}
        if not d:
            continue
        deltas = {c: v["matched"] - v["v1"] for c, v in d.items()}
        ex_m = [v for c, v in deltas.items() if c != "mischief"]
        n_drop = sum(1 for v in deltas.values() if v < -0.05)
        mis = deltas.get("mischief")
        w(f"| {model} | {np.mean(list(deltas.values())):+.3f} | {np.mean(ex_m):+.3f} | "
          f"{'—' if mis is None else f'{mis:+.3f}'} | {n_drop}/{len(deltas)} |")
    w()
    w("**Reading it:** a large negative mean Δ excluding mischief supports the "
      "methodological claim — the v1 numbers were inflated by unmatched controls. "
      "A mean Δ near zero with mischief already low means mischief is genuinely the "
      "hard class and the v1 controls, while sloppy, were not what produced that result.")
    w()
    w("**Lens vs representation:** where `h_tap vs matched` is much higher than "
      "`seed-space vs matched`, the disposition IS present in the hidden state and the "
      "seed-vector projection is discarding it — a fixable lens problem, not a model "
      "limit. Where both are low, the representation genuinely does not separate.")
    w()

    Path(args.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\nReport written to {args.out}")


if __name__ == "__main__":
    main()
