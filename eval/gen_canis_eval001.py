def main():
    parser = argparse.ArgumentParser(description="Generate CANIS-EVAL-001 prompt matrix")
    parser.add_argument("--out", default="eval/canis_eval001_matrix.jsonl")
    args = parser.parse_args()

    items = []
    counter = 1

    for cls in CLASSES:
        prompts = POSITIVES[cls]
        assert len(prompts) == 50, f"{cls}: expected 50 prompts, got {len(prompts)}"
        for prompt in prompts:
            items.append({
                "item_id": f"CEV001_{counter:04d}",
                "split": "positive",
                "target_class": cls,
                "prompt": prompt,
                "is_fp_test": False,
            })
            counter += 1

    assert len(IDLE_PROMPTS) == 50, f"idle: expected 50, got {len(IDLE_PROMPTS)}"
    for prompt in IDLE_PROMPTS:
        items.append({
            "item_id": f"CEV001_{counter:04d}",
            "split": "idle",
            "target_class": "idle",
            "prompt": prompt,
            "is_fp_test": False,
        })
        counter += 1

    for cls in CLASSES:
        prompts = NEGATIVES[cls]
        assert len(prompts) == 20, f"neg {cls}: expected 20 prompts, got {len(prompts)}"
        for prompt in prompts:
            items.append({
                "item_id": f"CEV001_{counter:04d}",
                "split": "negative",
                "target_class": cls,
                "prompt": prompt,
                "is_fp_test": True,
            })
            counter += 1

    out_path = pathlib.Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        for item in items:
            f.write(json.dumps(item) + "\n")

    n_pos  = sum(1 for i in items if i["split"] == "positive")
    n_idle = sum(1 for i in items if i["split"] == "idle")
    n_neg  = sum(1 for i in items if i["split"] == "negative")
    print(f"Written {len(items)} items to {out_path}")
    print(f"  positives : {n_pos}  (50 × {len(CLASSES)} classes)")
    print(f"  idle      : {n_idle}")
    print(f"  negatives : {n_neg}  (20 × {len(CLASSES)} classes)")
    assert len(items) == 540, f"Expected 540 items, got {len(items)}"
    print("  ✓ total = 540")


if __name__ == "__main__":
    main()
